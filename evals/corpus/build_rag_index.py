"""Build the packaged rewrite index. Not a runtime dependency of the checks.

    python evals/corpus/build_rag_index.py

Writes src/setup_doctor/explain/rag_index.py. The eval suite rebuilds the
plans in memory and fails if the committed module has drifted.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT))

from evals.detection.fixtures import ADVISORY_CASES, CASES  # noqa: E402
from setup_doctor import FixtureResolver, run_checks  # noqa: E402
from setup_doctor.checks.registry import ALL_DNS_PACKS  # noqa: E402

INDEX_PATH = ROOT / "src" / "setup_doctor" / "explain" / "rag_index.py"
_RECORD_RE = re.compile(r"v=(spf1|dmarc1|dkim1)", re.I)

Plan = tuple[tuple[str, str], ...]


def _from_cases(cases: list[dict], *, packs=None) -> list[Plan]:
    out: list[Plan] = []
    for case in cases:
        findings = run_checks(case["domain"], FixtureResolver(case["records"]), packs=packs)
        if not findings:
            continue
        out.append(tuple((f.id, f.why) for f in findings))
    return out


def _from_rewrite_pairs() -> list[Plan]:
    path = Path(__file__).resolve().parent / "rewrite_pairs.jsonl"
    out: list[Plan] = []
    for line in path.read_text().splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        out.append(tuple((item["id"], item["explanation"]) for item in row["plan"]))
    return out


def build_plans() -> tuple[Plan, ...]:
    """One plan per distinct finding-id set. Checker `why` wins over the jsonl on a clash.

    Domain names and DNS records are not stored. A plan whose explanation
    contains a DNS record is refused.
    """
    unique: dict[tuple[str, ...], Plan] = {}
    sources = (
        _from_cases(CASES)
        + _from_cases(ADVISORY_CASES, packs=ALL_DNS_PACKS)
        + _from_rewrite_pairs()
    )
    for plan in sources:
        for _fid, explanation in plan:
            if _RECORD_RE.search(explanation):
                raise RuntimeError(f"rewrite index explanation contains a DNS record: {explanation}")
        key = tuple(sorted(fid for fid, _ in plan))
        unique.setdefault(key, plan)
    return tuple(unique[key] for key in sorted(unique))


def render_module(plans: tuple[Plan, ...]) -> str:
    lines = [
        '"""Grounded rewrite examples for the explainer.',
        "",
        "Generated by evals/corpus/build_rag_index.py. Do not edit by hand.",
        "Each plan is (finding id, generic why). No DNS records and no source domains.",
        '"""',
        "from __future__ import annotations",
        "",
        "PLANS: tuple[tuple[tuple[str, str], ...], ...] = (",
    ]
    for plan in plans:
        lines.append("    (")
        for finding_id, explanation in plan:
            lines.append(f"        ({finding_id!r}, {explanation!r}),")
        lines.append("    ),")
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    plans = build_plans()
    INDEX_PATH.write_text(render_module(plans))
    print(f"wrote {INDEX_PATH} plans={len(plans)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
